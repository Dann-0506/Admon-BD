SET client_encoding = 'UTF8';
-- Ejecutado por dlandero en la segunda instancia, base de datos inversiones
BEGIN;
SET ROLE rol_admin_bd;

-- 1. Las tablas originales se conservan con otro nombre
ALTER TABLE pago RENAME TO pago_original;
ALTER TABLE pago_original RENAME CONSTRAINT pk_pago TO pk_pago_original;
ALTER TABLE bitacora RENAME TO bitacora_original;
ALTER TABLE bitacora_original
  RENAME CONSTRAINT pk_bitacora TO pk_bitacora_original;
ALTER SEQUENCE bitacora_bitacora_num_seq
  RENAME TO bitacora_original_bitacora_num_seq;

-- 2. Tablas particionadas, con la misma definición
CREATE TABLE pago (
  inversion_num          INT           NOT NULL,
  interes_fecha_inicial  DATE          NOT NULL,
  pago_fecha             DATE          NOT NULL,
  pago_interes           NUMERIC(14,2) NOT NULL,
  pago_mora              NUMERIC(14,2) NOT NULL DEFAULT 0,
  CONSTRAINT pk_pago
    PRIMARY KEY (inversion_num, interes_fecha_inicial, pago_fecha)
    USING INDEX TABLESPACE ts_operacion,
  CONSTRAINT fk_pago_interes FOREIGN KEY (inversion_num, interes_fecha_inicial)
    REFERENCES interes (inversion_num, interes_fecha_inicial)
    ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT ck_pago_montos CHECK (pago_interes >= 0 AND pago_mora >= 0)
) PARTITION BY RANGE (pago_fecha);

CREATE TABLE pago_2024 PARTITION OF pago
  FOR VALUES FROM (MINVALUE) TO ('2025-01-01') TABLESPACE ts_operacion;
CREATE TABLE pago_2025 PARTITION OF pago
  FOR VALUES FROM ('2025-01-01') TO ('2026-01-01') TABLESPACE ts_operacion;
CREATE TABLE pago_2026 PARTITION OF pago
  FOR VALUES FROM ('2026-01-01') TO ('2027-01-01') TABLESPACE ts_operacion;
CREATE TABLE pago_posterior PARTITION OF pago
  FOR VALUES FROM ('2027-01-01') TO (MAXVALUE) TABLESPACE ts_operacion;

CREATE TABLE bitacora (
  bitacora_num            BIGINT GENERATED BY DEFAULT AS IDENTITY,
  bitacora_fecha          TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
  bitacora_usuario        VARCHAR(100) NOT NULL,
  bitacora_tabla          VARCHAR(63)  NOT NULL,
  bitacora_operacion      VARCHAR(6)   NOT NULL,
  bitacora_ip             VARCHAR(45)  NULL,
  bitacora_sesion         BIGINT       NULL,
  bitacora_query          TEXT         NULL,
  bitacora_dato_anterior  JSONB        NULL,
  bitacora_dato_nuevo     JSONB        NULL,
  CONSTRAINT pk_bitacora PRIMARY KEY (bitacora_num, bitacora_fecha)
    USING INDEX TABLESPACE ts_bitacora,
  CONSTRAINT ck_bitacora_operacion
    CHECK (bitacora_operacion IN ('INSERT', 'UPDATE', 'DELETE'))
) PARTITION BY RANGE (bitacora_fecha);

CREATE TABLE bitacora_2026 PARTITION OF bitacora
  FOR VALUES FROM (MINVALUE) TO ('2027-01-01') TABLESPACE ts_bitacora;
CREATE TABLE bitacora_2027 PARTITION OF bitacora
  FOR VALUES FROM ('2027-01-01') TO ('2028-01-01') TABLESPACE ts_bitacora;
CREATE TABLE bitacora_posterior PARTITION OF bitacora
  FOR VALUES FROM ('2028-01-01') TO (MAXVALUE) TABLESPACE ts_bitacora;

-- 3. Copia de los datos y de la numeración de la bitácora
INSERT INTO pago SELECT * FROM pago_original;
INSERT INTO bitacora SELECT * FROM bitacora_original;
SELECT setval(pg_get_serial_sequence('bitacora', 'bitacora_num'),
              (SELECT MAX(bitacora_num) FROM bitacora));

-- 4. Eliminación de las tablas originales
DROP TABLE pago_original;
DROP TABLE bitacora_original;

-- 5. Bitácora: nombre de la tabla raíz y triggers de las nuevas tablas
CREATE OR REPLACE FUNCTION fn_bitacora()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = inversiones
AS $$
BEGIN
  INSERT INTO bitacora (bitacora_fecha, bitacora_usuario, bitacora_tabla,
                        bitacora_operacion, bitacora_ip, bitacora_sesion,
                        bitacora_query, bitacora_dato_anterior,
                        bitacora_dato_nuevo)
  VALUES (LOCALTIMESTAMP, session_user,
          COALESCE((SELECT relname FROM pg_class
                    WHERE oid = pg_partition_root(TG_RELID)),
                   TG_TABLE_NAME),
          TG_OP,
          host(inet_client_addr()), pg_backend_pid(), current_query(),
          CASE WHEN TG_OP IN ('UPDATE', 'DELETE') THEN to_jsonb(OLD) END,
          CASE WHEN TG_OP IN ('INSERT', 'UPDATE') THEN to_jsonb(NEW) END);
  RETURN NULL;
END;
$$;

CREATE TRIGGER trg_pago_bitacora
  AFTER INSERT OR UPDATE OR DELETE ON pago
  FOR EACH ROW EXECUTE FUNCTION fn_bitacora();

CREATE TRIGGER trg_bitacora_proteger
  BEFORE UPDATE OR DELETE ON bitacora
  FOR EACH ROW EXECUTE FUNCTION fn_bitacora_proteger();

CREATE TRIGGER trg_bitacora_truncate
  BEFORE TRUNCATE ON bitacora
  FOR EACH STATEMENT EXECUTE FUNCTION fn_bitacora_proteger();

-- 6. Privilegios de las nuevas tablas. El auditor y el usuario de respaldo
--    reciben los de las tablas por los privilegios por defecto, pero no
--    el de la nueva secuencia de la bitácora, que necesita pg_dump.
GRANT SELECT ON pago TO rol_gerente, rol_ejecutivo;
GRANT SELECT, INSERT ON pago TO rol_tesoreria;
GRANT SELECT ON SEQUENCE bitacora_bitacora_num_seq TO rol_respaldo;

COMMIT;

ANALYZE pago;
ANALYZE bitacora;
